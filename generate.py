"""Generate 240 frozen-input questions. Default operation is completely offline."""
import argparse
import csv
import hashlib
import io
import json
from pathlib import Path
from datetime import datetime, timezone
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parent
SOURCE = 'https://davidmegginson.github.io/ourairports-data/airports.csv'

def save_json(path, value):
    (ROOT / path).write_text(json.dumps(value, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')

def refresh():
    raw = urlopen(SOURCE, timeout=120).read()
    eligible = [r for r in csv.DictReader(io.StringIO(raw.decode('utf-8-sig')))
                if r['iso_country'] == 'US' and r['type'] == 'large_airport'
                and r['scheduled_service'] == 'yes'
                and 25 <= float(r['latitude_deg']) <= 49
                and -125 <= float(r['longitude_deg']) <= -66]
    rows = sorted(eligible, key=lambda r: r['ident'])[:40]
    assert len(rows) == 40
    fields = ['ident', 'name', 'latitude_deg', 'longitude_deg']
    with (ROOT / 'airports_subset.csv').open('w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()
        writer.writerows({k: r[k] for k in fields} for r in rows)
    save_json('source_manifest.json', {
        'source_url': SOURCE, 'source_page': 'https://ourairports.com/data/',
        'retrieved_utc': datetime.now(timezone.utc).isoformat(),
        'source_sha256': hashlib.sha256(raw).hexdigest(),
        'source_bytes': len(raw), 'license': 'Public domain per OurAirports terms',
        'selection': 'US; large_airport; scheduled_service=yes; latitude 25..49; longitude -125..-66; sort ident; first 40',
        'subset_sha256': hashlib.sha256((ROOT / 'airports_subset.csv').read_bytes()).hexdigest(),
        'synthetic_data': 'Original integer-coordinate fixtures generated by generate.py; CC0-1.0',
    })

def g(wkt, srid=3857):
    return f"ST_GeomFromText('{wkt}',{srid})"

def rectangle(x, y, size=10):
    return f'POLYGON(({x} {y},{x+size} {y},{x+size} {y+size},{x} {y+size},{x} {y}))'

def generate():
    airports = list(csv.DictReader((ROOT / 'airports_subset.csv').open(encoding='utf-8')))
    questions = []
    def add(task, i, prompt, context, sql, kind='set', expected=None):
        family = 'airport' if task in ['distance','radius','ranking','direction'] else 'synthetic'
        q = {'id': f'{task}_{i:02d}', 'scene_id': f'{family}_{i:02d}', 'task': task,
             'question': prompt, 'context': context, 'answer_type': kind, 'sql': sql}
        if expected is not None:
            q['fixture_expected'] = expected
        questions.append(q)
    for i, a in enumerate(airports[:30]):
        lon = round(float(a['longitude_deg']) + 0.13, 6)
        lat = round(float(a['latitude_deg']) + 0.07, 6)
        ref = f'ST_SetSRID(ST_MakePoint({lon},{lat}),4326)'
        d = f'ST_Distance(geom::geography,{ref}::geography)'
        ctx = {'source': 'OurAirports frozen subset', 'srid': 4326,
               'axis_order': 'longitude, latitude', 'reference': [lon, lat],
               'candidates': airports, 'distance': '2D spheroidal geography meters',
               'tie_policy': 'ascending distance then ident'}
        for task, limit in [('distance', 1), ('ranking', 3)]:
            sql = f"SELECT jsonb_agg(ident ORDER BY distance_m,ident) AS answer FROM (SELECT ident,{d} AS distance_m FROM airports ORDER BY distance_m,ident LIMIT {limit}) s"
            add(task, i, f'Return the {limit} nearest airport IDs to the reference, in ascending distance order. Break ties by ID.', ctx, sql, 'ordered')
        radius = [25000,100000,250000][i % 3]
        add('radius', i, f'Return every candidate airport ID at most {radius} meters from the reference. Return an empty array if none.',
            {**ctx, 'radius_m': radius}, f"SELECT COALESCE(jsonb_agg(ident ORDER BY ident),'[]'::jsonb) AS answer FROM airports WHERE ST_DWithin(geom::geography,{ref}::geography,{radius})")
        add('direction', i, 'Return every candidate airport ID northwest of the reference. Here northwest means strictly greater latitude AND strictly smaller longitude; this is a coordinate-quadrant test, not a bearing sector.',
            ctx, f"SELECT COALESCE(jsonb_agg(ident ORDER BY ident),'[]'::jsonb) AS answer FROM airports WHERE ST_Y(geom)>{lat} AND ST_X(geom)<{lon}")
    for i in range(30):
        x, y = i * 20, i * 10
        poly = rectangle(x,y)
        locations = [(x+5,y+5),(x,y+5),(x-1,y+5),(x,y),(x+11,y+5)]
        px, py = locations[i % len(locations)]
        point = f'POINT({px} {py})'
        ctx = {'source':'synthetic', 'srid':3857, 'units':'projected coordinate meters; artificial scene',
               'polygon':poly,'point':point}
        add('containment',i,'Is the point strictly inside the polygon? Boundary points do not count. Return true or false.',ctx,
            f'SELECT to_jsonb(ST_Contains({g(poly)},{g(point)})) AS answer','boolean',i%5 == 0)
        lines = [f'LINESTRING({x-2} {y+5},{x+12} {y+5})',
                 f'LINESTRING({x-2} {y},{x} {y})',
                 f'LINESTRING({x-2} {y-2},{x-1} {y-1})',
                 f'LINESTRING({x+2} {y+2},{x+8} {y+8})',
                 f'LINESTRING({x} {y},{x+10} {y})']
        line = lines[i%5]
        add('intersection',i,'Does the line share any point with the polygon? Boundary contact counts. Return true or false.',
            {**ctx,'line':line},f'SELECT to_jsonb(ST_Intersects({g(poly)},{g(line)})) AS answer','boolean',i%5 != 2)
        bx, by = [(x+10,y),(x+10,y+10),(x+11,y),(x+5,y),(x,y)][i%5]
        other = rectangle(bx,by)
        add('adjacency',i,'Do polygons A and B touch (boundaries meet and interiors do not intersect)? Corner-only contact counts. Return true or false.',
            {'source':'synthetic','srid':3857,'A':poly,'B':other},
            f'SELECT to_jsonb(ST_Touches({g(poly)},{g(other)})) AS answer','boolean',i%5 in [0,1])
        pts = [(f'P{j}', f'POINT({p[0]} {p[1]})') for j,p in enumerate(locations)]
        values = ','.join(f"('{pid}',{g(wkt)})" for pid,wkt in pts)
        radius = [2,8,12][i%3]
        sql = f"WITH p(id,geom) AS (VALUES {values}), ranked AS (SELECT id,ST_Distance(geom,{g(point)}) d FROM p WHERE ST_Contains({g(poly)},geom) AND ST_DWithin(geom,{g(point)},{radius})) SELECT COALESCE(jsonb_agg(id ORDER BY d,id),'[]'::jsonb) AS answer FROM ranked"
        add('multi_step',i,f'Return IDs of points strictly inside the polygon AND at most {radius} projected meters from the reference point. Order by distance then ID.',
            {**ctx,'reference_point':point,'candidates':dict(pts),'radius_m':radius},sql,'ordered', ['P0'] if ((px-(x+5))**2+(py-(y+5))**2)**0.5<=radius else [])
    questions.sort(key=lambda q:q['id'])
    (ROOT/'questions.jsonl').write_text(''.join(json.dumps(q,ensure_ascii=False)+'\n' for q in questions),encoding='utf-8')
    sql = '-- Generated by generate.py; each query returns one JSON answer.\n\n'
    sql += '\n\n'.join(f"-- {q['id']}: {q['question']}\n{q['sql']};" for q in questions)+'\n'
    (ROOT/'ground_truth.sql').write_text(sql,encoding='utf-8')
    save_json('airports.json',[{'id':a['ident'],'name':a['name'],'lon':float(a['longitude_deg']),'lat':float(a['latitude_deg'])} for a in airports])
    print(f'Generated {len(questions)} questions across {len(set(q["task"] for q in questions))} tasks.')

if __name__ == '__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--refresh-source', action='store_true', help='Download current source, replacing the frozen subset and manifest')
    args=parser.parse_args()
    if args.refresh_source:
        refresh()
    generate()
